"""Generate the plugin identity protocol's fixed Unicode 15.1 tables.

Run with Python whose unicodedata.unidata_version is 15.1.0 (Python 3.13).
Runtime normalization does not depend on the user's OS or Python installation.
Unicode character data is covered by https://www.unicode.org/license.txt.
"""
from pathlib import Path
import unicodedata as u

if u.unidata_version != "15.1.0":
    raise SystemExit("Unicode 15.1.0 required; do not silently change asset identities")

root = Path(__file__).resolve().parents[2]
out = ["// Generated by Tools/Plugins/GenerateUnicodeTables.py; Unicode 15.1.0.\n",
       "// Unicode data license: https://www.unicode.org/license.txt\n"]
decomp, combining, folds, compose = [], [], [], []
for cp in range(0x110000):
    char = chr(cp)
    raw = u.decomposition(char)
    if raw and not raw.startswith("<"):
        parts = [int(p, 16) for p in raw.split()]
        decomp.append((cp, parts))
        if len(parts) == 2 and u.normalize("NFC", "".join(map(chr, parts))) == char:
            compose.append((parts[0], parts[1], cp))
    if u.combining(char):
        combining.append((cp, u.combining(char)))
    folded = char.casefold()
    if folded != char:
        folds.append((cp, list(map(ord, folded))))

def mappings(name, entries):
    out.append(f"constexpr UnicodeMapping {name}[] = {{\n")
    for cp, seq in entries:
        assert len(seq) <= 3
        values = seq + [0] * (3 - len(seq))
        out.append(f"{{{cp}, {len(seq)}, {{{values[0]}, {values[1]}, {values[2]}}}}},\n")
    out.append("};\n")

mappings("kDecompositions", decomp)
mappings("kCaseFolds", folds)
out.append("constexpr UnicodeCombining kCombiningClasses[] = {\n")
out.extend(f"{{{cp}, {ccc}}},\n" for cp, ccc in combining)
out.append("};\nconstexpr UnicodeComposition kCompositions[] = {\n")
out.extend(f"{{{a}, {b}, {c}}},\n" for a, b, c in sorted(compose))
out.append("};\n")
(root / "Runtime/Core/Assets/PluginUnicodeData.inl").write_text("".join(out), encoding="utf-8")
